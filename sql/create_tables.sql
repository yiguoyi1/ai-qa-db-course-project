PROMPT Creating RECOMMENDATIONS...
-- 推荐结果表：保存已经生成的推荐候选和推荐原因。
-- rec_type/rec_source 用于解释推荐来源，便于用户中心和后台排查推荐结果。
CREATE TABLE recommendations (
    rec_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id         NUMBER             NOT NULL,
    question_id     NUMBER             NOT NULL,
    rec_type        VARCHAR2(50 CHAR)  NOT NULL,
    rec_source      VARCHAR2(50 CHAR),
    rec_reason      VARCHAR2(200 CHAR),
    rec_score       NUMBER(6,2)        DEFAULT 0 NOT NULL,
    rec_time        DATE               DEFAULT SYSDATE NOT NULL,
    status          VARCHAR2(20 CHAR)  DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT pk_recommendations PRIMARY KEY (rec_id),
    CONSTRAINT fk_recommendations_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_recommendations_question
        FOREIGN KEY (question_id) REFERENCES questions (question_id),
    CONSTRAINT ck_recommendations_type CHECK (
        rec_type IN ('TAG_BASED', 'POPULARITY', 'HYBRID', 'MANUAL')
    ),
    CONSTRAINT ck_recommendations_source CHECK (
        rec_source IS NULL OR rec_source IN (
            'USER_TAG_PROFILE',
            'POPULARITY',
            'USER_ACTION',
            'ADMIN_RULE',
            'MANUAL'
        )
    ),
    CONSTRAINT ck_recommendations_status CHECK (
        status IN ('ACTIVE', 'EXPIRED', 'DISMISSED')
    ),
    CONSTRAINT ck_recommendations_score CHECK (rec_score >= 0)
);

PROMPT Creating USER_TAG_PROFILE...
-- 用户标签画像表：由用户行为聚合生成，用 weight 表示用户对某个标签的兴趣强度。
-- 推荐算法会优先匹配用户画像中权重较高的标签。
CREATE TABLE user_tag_profile (
    profile_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id         NUMBER      NOT NULL,
    tag_id          NUMBER      NOT NULL,
    weight          NUMBER(6,2) DEFAULT 0       NOT NULL,
    update_time     DATE        DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_user_tag_profile PRIMARY KEY (profile_id),
    CONSTRAINT fk_user_tag_profile_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_user_tag_profile_tag
        FOREIGN KEY (tag_id) REFERENCES tags (tag_id),
    CONSTRAINT uq_user_tag_profile_pair UNIQUE (user_id, tag_id),
    CONSTRAINT ck_user_tag_profile_weight CHECK (weight >= 0)
);

PROMPT Creating CHAT_SESSION...
-- AI 追问会话表：围绕某个问题的 AI 首答继续追问。
-- seed_answer_id 指向被追问的 AI 首答，保证多轮对话有明确上下文。
CREATE TABLE chat_session (
    session_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id         NUMBER            NOT NULL,
    question_id     NUMBER            NOT NULL,
    seed_answer_id  NUMBER            NOT NULL,
    start_time      DATE              DEFAULT SYSDATE NOT NULL,
    end_time        DATE,
    status          VARCHAR2(20 CHAR) DEFAULT 'OPEN' NOT NULL,
    CONSTRAINT pk_chat_session PRIMARY KEY (session_id),
    CONSTRAINT fk_chat_session_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_chat_session_question
        FOREIGN KEY (question_id) REFERENCES questions (question_id),
    CONSTRAINT fk_chat_session_seed_answer
        FOREIGN KEY (question_id, seed_answer_id)
        REFERENCES answers (question_id, answer_id),
    CONSTRAINT ck_chat_session_status CHECK (status IN ('OPEN', 'CLOSED', 'ARCHIVED')),
    CONSTRAINT ck_chat_session_time CHECK (
        end_time IS NULL OR end_time >= start_time
    )
);

PROMPT Creating CHAT_MESSAGE...
CREATE TABLE chat_message (
    message_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    session_id      NUMBER            NOT NULL,
    sender_type     VARCHAR2(20 CHAR) NOT NULL,
    content         CLOB              NOT NULL,
    send_time       DATE              DEFAULT SYSDATE NOT NULL,
    model_name      VARCHAR2(50 CHAR),
    CONSTRAINT pk_chat_message PRIMARY KEY (message_id),
    CONSTRAINT fk_chat_message_session
        FOREIGN KEY (session_id) REFERENCES chat_session (session_id),
    CONSTRAINT ck_chat_message_sender CHECK (sender_type IN ('USER', 'AI', 'SYSTEM'))
);

