-- create_tables.sql
-- Oracle AI Database 26ai schema for the AI QA system

SET DEFINE OFF

-- 说明：本脚本定义问知社区的核心业务 schema。
-- 重点体现：用户与权限、问答内容、社区互动、媒体 BLOB、AI 调用日志、用户画像与推荐。

PROMPT Creating USERS...
-- 用户主表：保存登录账号、展示资料、角色和状态。
-- role 用于区分普通用户和管理员；status 用于支持封禁、停用和锁定。
CREATE TABLE users (
    user_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    username         VARCHAR2(50 CHAR)  NOT NULL,
    password_hash    VARCHAR2(100 CHAR) NOT NULL,
    nickname         VARCHAR2(50 CHAR),
    email            VARCHAR2(100 CHAR),
    phone            VARCHAR2(20 CHAR),
    role             VARCHAR2(20 CHAR)  DEFAULT 'USER'   NOT NULL,
    status           VARCHAR2(20 CHAR)  DEFAULT 'ACTIVE' NOT NULL,
    register_time    DATE               DEFAULT SYSDATE  NOT NULL,
    last_login_time  DATE,
    avatar_media_id  NUMBER,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'LOCKED', 'DISABLED'))
);

PROMPT Creating CATEGORIES...
-- 一级分类表：用于首页筛选和问题归类，数量应保持少而稳定。
-- 更细的主题应放在 TAGS 中，避免分类体系膨胀。
CREATE TABLE categories (
    category_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    category_name   VARCHAR2(50 CHAR)  NOT NULL,
    description     VARCHAR2(200 CHAR),
    status          VARCHAR2(20 CHAR)  DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT pk_categories PRIMARY KEY (category_id),
    CONSTRAINT uq_categories_name UNIQUE (category_name),
    CONSTRAINT ck_categories_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

PROMPT Creating TAGS...
-- 标签表：用于描述问题细分主题，可由系统、用户、AI 或管理员产生。
-- 标签比分类更灵活，是用户画像和推荐算法的重要输入。
CREATE TABLE tags (
    tag_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    tag_name        VARCHAR2(50 CHAR) NOT NULL,
    source          VARCHAR2(20 CHAR) DEFAULT 'SYSTEM' NOT NULL,
    status          VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    description     VARCHAR2(200 CHAR),
    create_user_id  NUMBER,
    create_time     DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_tags PRIMARY KEY (tag_id),
    CONSTRAINT uq_tags_name UNIQUE (tag_name),
    CONSTRAINT fk_tags_create_user
        FOREIGN KEY (create_user_id) REFERENCES users (user_id),
    CONSTRAINT ck_tags_source CHECK (source IN ('SYSTEM', 'USER', 'AI', 'ADMIN')),
    CONSTRAINT ck_tags_status CHECK (status IN ('ACTIVE', 'PENDING', 'DISABLED'))
);

PROMPT Creating MEDIA_ASSETS...
-- 统一媒体资源表：头像、问题配图、回答配图都存放在这里。
-- file_content 使用 BLOB 保存图片二进制，file_size 通过 CHECK 限制为 50MB 以内。
CREATE TABLE media_assets (
    media_id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    uploader_user_id       NUMBER             NOT NULL,
    owner_type             VARCHAR2(30 CHAR)  NOT NULL,
    owner_id               NUMBER             NOT NULL,
    file_name              VARCHAR2(120 CHAR) NOT NULL,
    original_file_name     VARCHAR2(255 CHAR),
    mime_type              VARCHAR2(100 CHAR) NOT NULL,
    file_ext               VARCHAR2(20 CHAR),
    file_size              NUMBER             DEFAULT 0        NOT NULL,
    storage_path           VARCHAR2(255 CHAR) NOT NULL,
    public_url             VARCHAR2(255 CHAR) NOT NULL,
    file_content           BLOB               NOT NULL,
    sort_order             NUMBER             DEFAULT 1        NOT NULL,
    status                 VARCHAR2(20 CHAR)  DEFAULT 'ACTIVE' NOT NULL,
    create_time            DATE               DEFAULT SYSDATE  NOT NULL,
    update_time            DATE               DEFAULT SYSDATE  NOT NULL,
    delete_time            DATE,
    CONSTRAINT pk_media_assets PRIMARY KEY (media_id),
    CONSTRAINT uq_media_assets_file_name UNIQUE (file_name),
    CONSTRAINT fk_media_assets_uploader
        FOREIGN KEY (uploader_user_id) REFERENCES users (user_id),
    CONSTRAINT ck_media_assets_owner_type CHECK (
        owner_type IN ('USER_AVATAR', 'QUESTION', 'ANSWER')
    ),
    CONSTRAINT ck_media_assets_status CHECK (
        status IN ('ACTIVE', 'DELETED')
    ),
    CONSTRAINT ck_media_assets_file_size CHECK (file_size BETWEEN 0 AND 52428800),
    CONSTRAINT ck_media_assets_sort_order CHECK (sort_order >= 1),
    CONSTRAINT ck_media_assets_delete_time CHECK (
        delete_time IS NULL OR delete_time >= create_time
    )
);

PROMPT Linking USERS avatar to MEDIA_ASSETS...
ALTER TABLE users
ADD CONSTRAINT fk_users_avatar_media
    FOREIGN KEY (avatar_media_id) REFERENCES media_assets (media_id);

PROMPT Creating QUESTIONS...
-- 问题主表：保存提问者、分类、标题、正文和问题状态。
-- view_count、favorite_count、answer_count 是冗余统计字段，由触发器和存储过程同步维护。
CREATE TABLE questions (
    question_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id          NUMBER             NOT NULL,
    category_id      NUMBER             NOT NULL,
    title            VARCHAR2(200 CHAR) NOT NULL,
    content          CLOB               NOT NULL,
    ask_time         DATE               DEFAULT SYSDATE NOT NULL,
    status           VARCHAR2(20 CHAR)  DEFAULT 'OPEN' NOT NULL,
    accepted_answer_id NUMBER,
    view_count       NUMBER             DEFAULT 0       NOT NULL,
    favorite_count   NUMBER             DEFAULT 0       NOT NULL,
    answer_count     NUMBER             DEFAULT 0       NOT NULL,
    CONSTRAINT pk_questions PRIMARY KEY (question_id),
    CONSTRAINT fk_questions_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_questions_category
        FOREIGN KEY (category_id) REFERENCES categories (category_id),
    CONSTRAINT ck_questions_status CHECK (status IN ('OPEN', 'RESOLVED', 'CLOSED', 'ARCHIVED', 'DELETED')),
    CONSTRAINT ck_questions_view_count CHECK (view_count >= 0),
    CONSTRAINT ck_questions_favorite_count CHECK (favorite_count >= 0),
    CONSTRAINT ck_questions_answer_count CHECK (answer_count >= 0)
);

PROMPT Creating ANSWERS...
-- 回答表：同时支持 AI 回答、人工回答和系统回答。
-- ck_answers_user_presence 保证人工回答必须有 user_id，而 AI/SYSTEM 回答不绑定用户。
CREATE TABLE answers (
    answer_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    question_id        NUMBER             NOT NULL,
    user_id            NUMBER,
    answer_type        VARCHAR2(20 CHAR)  NOT NULL,
    provider_name      VARCHAR2(50 CHAR),
    content            CLOB               NOT NULL,
    generate_time      DATE               DEFAULT SYSDATE NOT NULL,
    status             VARCHAR2(20 CHAR)  DEFAULT 'ACTIVE' NOT NULL,
    delete_time        DATE,
    model_name         VARCHAR2(50 CHAR),
    confidence_score   NUMBER(5,2),
    like_count         NUMBER             DEFAULT 0       NOT NULL,
    dislike_count      NUMBER             DEFAULT 0       NOT NULL,
    avg_rating         NUMBER(3,2),
    CONSTRAINT pk_answers PRIMARY KEY (answer_id),
    CONSTRAINT uq_answers_question_answer UNIQUE (question_id, answer_id),
    CONSTRAINT fk_answers_question
        FOREIGN KEY (question_id) REFERENCES questions (question_id),
    CONSTRAINT fk_answers_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_answers_type CHECK (answer_type IN ('AI', 'MANUAL', 'SYSTEM')),
    CONSTRAINT ck_answers_user_presence CHECK (
        (answer_type = 'MANUAL' AND user_id IS NOT NULL)
        OR (answer_type IN ('AI', 'SYSTEM') AND user_id IS NULL)
    ),
    CONSTRAINT ck_answers_status CHECK (status IN ('ACTIVE', 'HIDDEN', 'DELETED')),
    CONSTRAINT ck_answers_delete_time CHECK (
        delete_time IS NULL OR delete_time >= generate_time
    ),
    CONSTRAINT ck_answers_confidence CHECK (
        confidence_score IS NULL OR (confidence_score >= 0 AND confidence_score <= 100)
    ),
    CONSTRAINT ck_answers_like_count CHECK (like_count >= 0),
    CONSTRAINT ck_answers_dislike_count CHECK (dislike_count >= 0),
    CONSTRAINT ck_answers_avg_rating CHECK (
        avg_rating IS NULL OR (avg_rating >= 0 AND avg_rating <= 5)
    )
);

ALTER TABLE questions
    -- 复合外键保证“采纳答案”必须属于当前问题，避免把其他问题的答案误采纳。
    ADD CONSTRAINT fk_questions_accepted_answer
        FOREIGN KEY (question_id, accepted_answer_id)
        REFERENCES answers (question_id, answer_id);

PROMPT Creating QUESTION_TAGS...
-- 问题与标签的多对多关系表。
-- source 和 confidence_score 用于区分用户选择、用户创建、AI 匹配、AI 创建和管理员调整。
CREATE TABLE question_tags (
    qt_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    question_id     NUMBER NOT NULL,
    tag_id          NUMBER NOT NULL,
    source          VARCHAR2(30 CHAR) DEFAULT 'USER_SELECTED' NOT NULL,
    confidence_score NUMBER(5,2),
    create_time     DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_question_tags PRIMARY KEY (qt_id),
    CONSTRAINT fk_question_tags_question
        FOREIGN KEY (question_id) REFERENCES questions (question_id),
    CONSTRAINT fk_question_tags_tag
        FOREIGN KEY (tag_id) REFERENCES tags (tag_id),
    CONSTRAINT uq_question_tags_pair UNIQUE (question_id, tag_id),
    CONSTRAINT ck_question_tags_source CHECK (
        source IN ('USER_SELECTED', 'USER_CREATED', 'AI_MATCHED', 'AI_CREATED', 'ADMIN_ADJUSTED')
    ),
    CONSTRAINT ck_question_tags_confidence CHECK (
        confidence_score IS NULL OR (confidence_score >= 0 AND confidence_score <= 100)
    )
);

PROMPT Creating ANSWER_FEEDBACK...
CREATE TABLE answer_feedback (
    feedback_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    answer_id        NUMBER             NOT NULL,
    user_id          NUMBER             NOT NULL,
    is_like          VARCHAR2(10 CHAR)  NOT NULL,
    rating           NUMBER(2,1),
    comment_text     VARCHAR2(500 CHAR),
    feedback_time    DATE               DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_answer_feedback PRIMARY KEY (feedback_id),
    CONSTRAINT fk_answer_feedback_answer
        FOREIGN KEY (answer_id) REFERENCES answers (answer_id),
    CONSTRAINT fk_answer_feedback_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_answer_feedback_like CHECK (is_like IN ('Y', 'N')),
    CONSTRAINT ck_answer_feedback_rating CHECK (
        rating IS NULL OR (rating >= 0 AND rating <= 5)
    ),
    CONSTRAINT uq_answer_feedback_answer_user UNIQUE (answer_id, user_id)
);

PROMPT Creating ANSWER_COMMENTS...
-- 回答评论表：通过 parent_comment_id/root_comment_id 支持楼中楼回复。
-- 删除采用软删除，保留评论关系链，前端可展示“原评论/回复已删除”。
CREATE TABLE answer_comments (
    comment_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    answer_id          NUMBER             NOT NULL,
    user_id            NUMBER             NOT NULL,
    parent_comment_id  NUMBER,
    root_comment_id    NUMBER,
    reply_to_user_id   NUMBER,
    content            CLOB               NOT NULL,
    comment_level      NUMBER             DEFAULT 1        NOT NULL,
    status             VARCHAR2(20 CHAR)  DEFAULT 'ACTIVE' NOT NULL,
    reply_count        NUMBER             DEFAULT 0        NOT NULL,
    create_time        DATE               DEFAULT SYSDATE  NOT NULL,
    update_time        DATE               DEFAULT SYSDATE  NOT NULL,
    delete_time        DATE,
    CONSTRAINT pk_answer_comments PRIMARY KEY (comment_id),
    CONSTRAINT fk_answer_comments_answer
        FOREIGN KEY (answer_id) REFERENCES answers (answer_id),
    CONSTRAINT fk_answer_comments_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_answer_comments_parent
        FOREIGN KEY (parent_comment_id) REFERENCES answer_comments (comment_id),
    CONSTRAINT fk_answer_comments_root
        FOREIGN KEY (root_comment_id) REFERENCES answer_comments (comment_id),
    CONSTRAINT fk_answer_comments_reply_user
        FOREIGN KEY (reply_to_user_id) REFERENCES users (user_id),
    CONSTRAINT ck_answer_comments_level CHECK (comment_level >= 1),
    CONSTRAINT ck_answer_comments_status CHECK (status IN ('ACTIVE', 'HIDDEN', 'DELETED')),
    CONSTRAINT ck_answer_comments_reply_count CHECK (reply_count >= 0),
    CONSTRAINT ck_answer_comments_delete_time CHECK (
        delete_time IS NULL OR delete_time >= create_time
    )
);

